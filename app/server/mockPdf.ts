/**
 * Builds a one-page PDF with a title, a few lines of text and a footer. The
 * seed uses it for mock documents and receipts; the server uses it for payment
 * acknowledgments.
 */
export function mockPdf(title: string, lines: string[], footer = 'DEMO DOCUMENT - generated by the Tutors To Go seed. Not a real record.') {
  // Standard Type 1 fonts only cover Latin-1, so replace anything else.
  const esc = (s: string) => s.replace(/[^\x20-\x7e]/g, '-').replace(/[\\()]/g, (c) => `\\${c}`);
  const text = [
    'BT /F1 20 Tf 72 740 Td',
    `(${esc(title)}) Tj`,
    '/F1 12 Tf 0 -36 Td 18 TL',
    ...lines.map((l) => `(${esc(l)}) Tj T*`),
    `0 -36 Td /F1 10 Tf (${esc(footer)}) Tj`,
    'ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(text, 'latin1')} >>\nstream\n${text}\nendstream`,
  ];
  let out = '%PDF-1.4\n';
  const offsets = objects.map((body, i) => {
    const at = Buffer.byteLength(out, 'latin1');
    out += `${i + 1} 0 obj\n${body}\nendobj\n`;
    return at;
  });
  const xref = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}
